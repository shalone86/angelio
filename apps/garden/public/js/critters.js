/** Return approved critter variants for `species`, falling back to `bug` variants if unknown. */
export function variantsOf(species) {
  const list = GARDEN_CRITTERS.filter((c) => c.species === species);
  return list.length ? list : GARDEN_CRITTERS.filter((c) => c.species === "bug");
}

/** Look up a critter variant definition by its unique `id`. */
export function critterVariantById(id) {
  return GARDEN_CRITTERS.find((c) => c.id === id) ?? null;
}

/** Build a Three.js Group for a Garden critter variant using bottom-anchored `[w, h, d, x, y, z, color, emissive?]` tuples. */
export function buildCritterGroup(THREE, variant, { box, mat, basicMat }) {
  const g = new THREE.Group();
  for (const [w, h, d, x, y, z, color, emissive] of variant.boxes) {
    const m = emissive ? basicMat(color) : mat(color);
    const mesh = new THREE.Mesh(box, m);
    mesh.scale.set(w, h, d);
    mesh.position.set(x, y + h / 2, z);
    g.add(mesh);
  }
  g.userData.frames = [];
  g.userData.variantId = variant.id;
  return g;
}
